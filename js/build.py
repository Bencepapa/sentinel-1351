"""Export the native C128 tests for the JS runtime.

Runs each test's own build.py (so the PRG is current), assembles its source
once more to get the symbol table, and writes js/programs.js:

    SENTINEL_PROGRAMS = { flight: {load, entry, prg: base64, symbols: {...}}, ... }

The JS side hooks routines by label, never by hard-coded address, so the hooks
keep working when the C128 code moves.
"""

import base64
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, os.path.join(ROOT, 'mouse', 'tools'))
from asm import asm  # noqa: E402

TESTS = {
    'flight': ('c128-flight', 'flight.asm', 'sentinel-c128-flight.prg'),
    'map': ('c128-map', 'map.asm', 'sentinel-c128-map.prg'),
    'cockpit': (os.path.join('c128-gui', 'cockpit'), 'cockpit.asm', 'sentinel-c128-cockpit.prg'),
}


def export(name, folder, source, prg):
    path = os.path.join(ROOT, folder)
    subprocess.run([sys.executable, os.path.join(path, 'build.py')], check=True)
    with open(os.path.join(path, source), encoding='ascii') as f:
        chunks, symbols = asm(f.read())
    with open(os.path.join(path, prg), 'rb') as f:
        data = f.read()
    load = data[0] | data[1] << 8
    return {
        'load': load,
        'entry': symbols['START'],
        'code': [min(chunks), max(a + len(b) for a, b in chunks.items())],
        'prg': base64.b64encode(data).decode('ascii'),
        'symbols': dict(sorted(symbols.items(), key=lambda kv: kv[1])),
    }


def main():
    out = {name: export(name, *spec) for name, spec in TESTS.items()}
    target = os.path.join(HERE, 'programs.js')
    with open(target, 'w', encoding='ascii') as f:
        f.write('// Generated by js/build.py - do not edit.\n')
        f.write('var SENTINEL_PROGRAMS = ')
        json.dump(out, f, indent=1)
        f.write(';\n')
    for name, p in out.items():
        print(f'{name}: load ${p["load"]:04X}, entry ${p["entry"]:04X}, '
              f'{len(p["symbols"])} symbols')
    print(f'wrote {target}')


if __name__ == '__main__':
    main()
